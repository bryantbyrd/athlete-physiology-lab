#!/usr/bin/env python3
"""Generate a SYNTHETIC overnight recording in the SensorForge Pro export layout.

The output is produced by a simple random model. It is not a physiological
simulation and it is not derived from any real recording. Use it to exercise
the import script, the workbook template and (later) the Python analysis code
without touching personal data.

Layout written (see docs/data-format.md):

    <out>/SF_<YYYYMMDD-HHMMSS>_Polar-H10-<ID>/
        <ID>_hr.csv     one row per heart-rate notification (about 1 Hz)
        <ID>_rr.csv     one row per R-R interval
        markers.csv     header only
        session.json    minimal, synthetic metadata

With --zip the session folder is also packed into <out>/SF_..._<ID>.zip.

Standard library only. Deterministic for a given --seed.
"""

from __future__ import annotations

import argparse
import json
import math
import random
import zipfile
from datetime import datetime, timezone
from pathlib import Path

HR_HEADER = (
    "rx_unix_ms,frame,hr_bpm,corrected_hr_bpm,ppg_quality,"
    "rr_available,contact,contact_supported"
)
RR_HEADER = "rx_unix_ms,frame,rr_ms"


def synth_rr(hours: float, rng: random.Random) -> list[int]:
    """Return a list of R-R intervals (ms) covering roughly `hours` hours."""
    total_ms = hours * 3_600_000
    rr: list[int] = []
    t = 0.0
    noise = 0.0
    while t < total_ms:
        phase = t / total_ms
        # Slow overnight trend: mean interval lengthens towards mid-recording.
        mean = 950 + 220 * math.sin(math.pi * phase)
        # Respiratory-frequency oscillation (about 0.25 Hz) plus correlated noise.
        rsa = 35 * math.sin(2 * math.pi * 0.25 * t / 1000)
        noise = 0.9 * noise + rng.gauss(0, 8)
        value = mean + rsa + noise + rng.gauss(0, 6)
        # Occasional artefacts so the screening logic has something to flag.
        roll = rng.random()
        if roll < 0.002:
            value *= 2.0  # missed beat
        elif roll < 0.004:
            value *= 0.5  # extra detection
        interval = max(250, int(round(value)))
        rr.append(interval)
        t += interval
    return rr


def build_rows(rr: list[int], start_ms: int, rng: random.Random):
    """Assign R-R intervals to ~1 Hz notification frames."""
    beat_end = []
    t = 0
    for interval in rr:
        t += interval
        beat_end.append(t)

    hr_rows, rr_rows = [], []
    frame, frame_t, i = 0, 0, 0
    last_hr = 60
    while i < len(rr):
        intervals = []
        while i < len(rr) and beat_end[i] <= frame_t + 1000:
            intervals.append(rr[i])
            i += 1
        rx = start_ms + frame_t + rng.randint(-8, 8)
        if intervals:
            last_hr = int(round(60000 / (sum(intervals) / len(intervals))))
        hr_rows.append(
            f"{rx},{frame},{last_hr},{last_hr},0,{1 if intervals else 0},0,0"
        )
        rr_rows.extend(f"{rx},{frame},{interval}" for interval in intervals)
        frame += 1
        frame_t += 1000
    return hr_rows, rr_rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True, help="output folder")
    parser.add_argument("--device-id", default="00000000",
                        help="placeholder sensor ID (default: 00000000)")
    parser.add_argument("--hours", type=float, default=7.0)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--start", default="2020-01-01T06:00:00",
                        help="recording start, UTC, ISO 8601 (default: %(default)s)")
    parser.add_argument("--zip", action="store_true",
                        help="also write a SensorForge-style ZIP archive")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    start = datetime.fromisoformat(args.start).replace(tzinfo=timezone.utc)
    start_ms = int(start.timestamp() * 1000)
    name = f"SF_{start:%Y%m%d-%H%M%S}_Polar-H10-{args.device_id}"
    folder = args.out / name
    folder.mkdir(parents=True, exist_ok=True)

    rr = synth_rr(args.hours, rng)
    hr_rows, rr_rows = build_rows(rr, start_ms, rng)

    files = {
        f"{args.device_id}_hr.csv": "\n".join([HR_HEADER, *hr_rows]) + "\n",
        f"{args.device_id}_rr.csv": "\n".join([RR_HEADER, *rr_rows]) + "\n",
        "markers.csv": "unix_time_ms,label\n",
        "session.json": json.dumps(
            {
                "formatVersion": 1,
                "synthetic": True,
                "note": "Generated by tools/make_synthetic_night.py; not real data.",
                "startedAt": start.isoformat().replace("+00:00", "Z"),
                "devices": [{"id": args.device_id, "model": "H10"}],
                "seed": args.seed,
            },
            indent=2,
        ) + "\n",
    }
    for filename, text in files.items():
        (folder / filename).write_text(text, encoding="utf-8", newline="\n")

    if args.zip:
        with zipfile.ZipFile(args.out / f"{name}.zip", "w", zipfile.ZIP_DEFLATED) as zf:
            for filename in files:
                zf.write(folder / filename, f"{name}/{filename}")

    print(f"{name}: {len(hr_rows)} HR rows, {len(rr_rows)} RR intervals (synthetic)")


if __name__ == "__main__":
    main()
